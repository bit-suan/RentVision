import type { SupportedLocale } from './locale';

/**
 * Roles accepted by the general-purpose RentVision assistant endpoint.
 *
 * The assistant is intentionally limited to conversation text. Listings,
 * verification data, and lease documents are never sent through this contract.
 */
export type AssistantChatRole = 'user' | 'assistant';

export interface AssistantChatMessage {
  role: AssistantChatRole;
  content: string;
}

export interface AssistantChatRequest {
  messages: AssistantChatMessage[];
  locale?: SupportedLocale;
}

export interface AssistantChatResponse {
  /** Plain-text answer generated by the configured model provider. */
  reply: string;
  /** Provider name is informational only and must never include credentials. */
  provider?: string;
  /** Model name is informational only. */
  model?: string;
}

export type AssistantChatErrorCode =
  | 'bad_request'
  | 'not_configured'
  | 'timeout'
  | 'rate_limited'
  | 'upstream_error'
  | 'unavailable'
  | 'empty_response'
  | 'network_error';

export interface AssistantChatErrorBody {
  error: {
    code: AssistantChatErrorCode;
    message: string;
    retryable: boolean;
  };
}
